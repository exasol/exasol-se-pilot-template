CREATE OR REPLACE VIEW <PILOT_SCHEMA>.FACT_PRIMARY_MEASURES AS
WITH c AS (SELECT * FROM <PILOT_SCHEMA>.FACT_PRIMARY_SOURCE)
SELECT
    c.*,
    CASE WHEN UNIT_VALUE <> 0 THEN (
      GROSS_MARGIN/UNIT_VALUE
    ) ELSE null END AS GROSS_MARGIN_PERCENT,
    UNIT_VALUE - (SELECT SUM(SALESBUDGET) FROM <PILOT_SCHEMA>.FACT_TARGET) AS TARGET_VARIANCE,
    CASE WHEN UNIT_VALUE <> 0 THEN (
      (UNIT_VALUE - (SELECT SUM(SALESBUDGET) FROM <PILOT_SCHEMA>.FACT_TARGET))/UNIT_VALUE
    ) ELSE null END AS TARGET_VARIANCE_PERCENT,
    RATIO_TO_REPORT(UNIT_VALUE) OVER (PARTITION BY CATALOG_DATE) AS SALESCATDATEPCT,
    RATIO_TO_REPORT(UNIT_VALUE) OVER (PARTITION BY SERIES_DESC) AS SALESSERIESPCT
FROM c;

CREATE OR REPLACE VIEW <PILOT_SCHEMA>.V_MONTHLY_METRICS AS
WITH monthly AS (
    SELECT
        EXTRACT(YEAR  FROM i.INVOICE_DATE)  AS PERIOD_YEAR,
        EXTRACT(MONTH FROM i.INVOICE_DATE)  AS PERIOD_MONTH,
        d.QUARTER_BY_YEAR,
        r.XYZ_REGION_1,
        r.XYZ_REGION_2,
        pg.SEGMENT,
        pg.SERIES_DESC,
        pg.SUBCATEGORY,
        pg.PRODUCT_LINE_NAME,
        SUM(i.UNIT_VALUE)     AS MONTHLY_VALUE,
        SUM(i.COGS_AMOUNT)     AS MONTHLY_COGS,
        SUM(i.GROSS_MARGIN)    AS MONTHLY_GROSS_MARGIN,
        SUM(i.QTY_SHIPPED)     AS MONTHLY_QTY,
        SUM(i.SALES_PRICE_CAD) AS MONTHLY_VALUE_CAD
    FROM <PILOT_SCHEMA>.FACT_PRIMARY i
    LEFT JOIN <PILOT_SCHEMA>."DATE"      d  ON i.INVOICEDATEKEY  = d."DATE"
    LEFT JOIN <PILOT_SCHEMA>.DIM_REGION r ON i.REGION_KEY       = r.REGION_KEY
    LEFT JOIN <PILOT_SCHEMA>.DIM_CATEGORY pg ON i.CATEGORY_KEY = pg.CATEGORY_KEY
    GROUP BY 1,2,3,4,5,6,7,8,9
)
SELECT
    m.*,
    SUM(m.MONTHLY_VALUE) OVER (
        PARTITION BY m.PERIOD_YEAR, m.XYZ_REGION_1, m.SEGMENT
        ORDER BY m.PERIOD_MONTH
        ROWS UNBOUNDED PRECEDING
    ) AS YTD_VALUE,
    SUM(m.MONTHLY_QTY) OVER (
        PARTITION BY m.PERIOD_YEAR, m.XYZ_REGION_1, m.SEGMENT
        ORDER BY m.PERIOD_MONTH
        ROWS UNBOUNDED PRECEDING
    ) AS YTD_QTY,
    SUM(m.MONTHLY_VALUE) OVER (
        PARTITION BY m.XYZ_REGION_1, m.SEGMENT
        ORDER BY m.PERIOD_YEAR, m.PERIOD_MONTH
        ROWS BETWEEN 2 PRECEDING AND CURRENT ROW
    ) AS ROLLING_3M_VALUE,
    SUM(m.MONTHLY_VALUE) OVER (
        PARTITION BY m.XYZ_REGION_1, m.SEGMENT
        ORDER BY m.PERIOD_YEAR, m.PERIOD_MONTH
        ROWS BETWEEN 5 PRECEDING AND CURRENT ROW
    ) AS ROLLING_6M_VALUE,
    CASE WHEN m.MONTHLY_VALUE <> 0
         THEN m.MONTHLY_GROSS_MARGIN / m.MONTHLY_VALUE
         ELSE NULL
    END AS GROSS_MARGIN_PCT,
    RATIO_TO_REPORT(m.MONTHLY_VALUE) OVER (
        PARTITION BY m.PERIOD_YEAR, m.PERIOD_MONTH, m.SEGMENT
    ) AS SALES_PCT_OF_BRAND,
    RATIO_TO_REPORT(m.MONTHLY_VALUE) OVER (
        PARTITION BY m.PERIOD_YEAR, m.PERIOD_MONTH, m.XYZ_REGION_1
    ) AS SALES_PCT_OF_REGION
FROM monthly m;

CREATE OR REPLACE VIEW <PILOT_SCHEMA>.V_YOY_METRICS AS
SELECT
    cy.PERIOD_YEAR,
    cy.PERIOD_MONTH,
    cy.QUARTER_BY_YEAR,
    cy.XYZ_REGION_1,
    cy.XYZ_REGION_2,
    cy.SEGMENT,
    cy.SUBCATEGORY,
    cy.MONTHLY_VALUE                          AS SALES_CY,
    cy.MONTHLY_QTY                            AS QTY_CY,
    cy.MONTHLY_GROSS_MARGIN                   AS GM_CY,
    py.MONTHLY_VALUE                          AS SALES_PY,
    py.MONTHLY_QTY                            AS QTY_PY,
    cy.MONTHLY_VALUE - py.MONTHLY_VALUE       AS SALES_YOY_VAR,
    CASE WHEN py.MONTHLY_VALUE <> 0
         THEN (cy.MONTHLY_VALUE - py.MONTHLY_VALUE) / py.MONTHLY_VALUE
         ELSE NULL END                         AS SALES_YOY_PCT,
    CASE WHEN py.MONTHLY_QTY <> 0
         THEN (cy.MONTHLY_QTY - py.MONTHLY_QTY) / py.MONTHLY_QTY
         ELSE NULL END                         AS QTY_YOY_PCT
FROM <PILOT_SCHEMA>.V_MONTHLY_METRICS cy
LEFT JOIN <PILOT_SCHEMA>.V_MONTHLY_METRICS py
       ON cy.PERIOD_MONTH  = py.PERIOD_MONTH
      AND cy.PERIOD_YEAR   = py.PERIOD_YEAR + 1
      AND cy.XYZ_REGION_1   = py.XYZ_REGION_1
      AND cy.SEGMENT          = py.SEGMENT
      AND cy.SUBCATEGORY   = py.SUBCATEGORY;

CREATE OR REPLACE VIEW <PILOT_SCHEMA>.V_ACTUAL_VS_TARGET AS
SELECT
    ms.PERIOD_YEAR,
    ms.PERIOD_MONTH,
    ms.XYZ_REGION_1,
    ms.SEGMENT,
    ms.SUBCATEGORY,
    ms.MONTHLY_VALUE                               AS ACTUAL_VALUE,
    ms.YTD_VALUE                                   AS YTD_ACTUAL,
    ms.GROSS_MARGIN_PCT,
    SUM(t.SALESBUDGET)                             AS MONTHLY_TARGET,
    SUM(t.SALESBUDGET) OVER (
        PARTITION BY ms.PERIOD_YEAR, ms.XYZ_REGION_1, ms.SEGMENT
        ORDER BY ms.PERIOD_MONTH
        ROWS UNBOUNDED PRECEDING
    )                                              AS YTD_TARGET,
    ms.MONTHLY_VALUE - SUM(t.SALESBUDGET)          AS TARGET_VARIANCE,
    CASE WHEN SUM(t.SALESBUDGET) <> 0
         THEN (ms.MONTHLY_VALUE - SUM(t.SALESBUDGET)) / SUM(t.SALESBUDGET)
         ELSE NULL
    END                                            AS TARGET_VARIANCE_PCT,
    ms.YTD_VALUE - SUM(t.SALESBUDGET) OVER (
        PARTITION BY ms.PERIOD_YEAR, ms.XYZ_REGION_1, ms.SEGMENT
        ORDER BY ms.PERIOD_MONTH ROWS UNBOUNDED PRECEDING
    )                                              AS YTD_TARGET_VARIANCE
FROM <PILOT_SCHEMA>.V_MONTHLY_METRICS ms
LEFT JOIN <PILOT_SCHEMA>.FACT_TARGET t
       ON t.FISCAL_YEAR   = ms.PERIOD_YEAR
      AND t.FISCAL_PERIOD = ms.PERIOD_MONTH
GROUP BY 1,2,3,4,5,6,7,8,ms.YTD_VALUE;

CREATE OR REPLACE VIEW <PILOT_SCHEMA>.V_STOCK_ANALYTICS AS
WITH inv_snap AS (
    SELECT
        inv.INVENTORY_DATE,
        EXTRACT(YEAR  FROM inv.INVENTORY_DATE) AS INV_YEAR,
        EXTRACT(MONTH FROM inv.INVENTORY_DATE) AS INV_MONTH,
        p.SEGMENT,
        p.SERIES_DESC,
        p.SUBCATEGORY,
        p.ITEM_ID,
        SUM(inv.QTY_ON_HAND)        AS QTY_ON_HAND,
        SUM(inv.QTY_AVAILABLE)      AS QTY_AVAILABLE,
        SUM(inv.COSTONHAND)         AS INV_COST,
        SUM(inv.QTY_ON_ORDER) AS ON_ORDER
    FROM <PILOT_SCHEMA>.FACT_STOCK inv
    LEFT JOIN <PILOT_SCHEMA>.DIM_ITEM p ON inv.PRODUCTKEY = p.SKU
    GROUP BY 1,2,3,4,5,6,7
),
sales_365 AS (
    SELECT
        EXTRACT(YEAR  FROM i.INVOICE_DATE) AS S_YEAR,
        EXTRACT(MONTH FROM i.INVOICE_DATE) AS S_MONTH,
        p.SEGMENT,
        p.SUBCATEGORY,
        SUM(i.COGS_AMOUNT)  AS COGS_ROLLING_365,
        SUM(i.QTY_SHIPPED)  AS QTY_SOLD_365
    FROM <PILOT_SCHEMA>.FACT_PRIMARY i
    LEFT JOIN <PILOT_SCHEMA>.DIM_ITEM p ON i.PRODUCTKEY = p.SKU
    GROUP BY 1,2,3,4
)
SELECT
    s.INVENTORY_DATE,
    s.SEGMENT,
    s.SUBCATEGORY,
    s.QTY_ON_HAND,
    s.QTY_AVAILABLE,
    s.INV_COST,
    s.ON_ORDER,
    r.COGS_ROLLING_365,
    r.QTY_SOLD_365,
    CASE WHEN AVG(s.INV_COST) OVER (
              PARTITION BY s.SEGMENT, s.SUBCATEGORY
              ORDER BY s.INVENTORY_DATE
              ROWS BETWEEN 11 PRECEDING AND CURRENT ROW) <> 0
         THEN r.COGS_ROLLING_365 /
              AVG(s.INV_COST) OVER (
              PARTITION BY s.SEGMENT, s.SUBCATEGORY
              ORDER BY s.INVENTORY_DATE
              ROWS BETWEEN 11 PRECEDING AND CURRENT ROW)
         ELSE NULL END AS INV_VALUE_TURNS,
    CASE WHEN NULLIFZERO(r.QTY_SOLD_365 / 365.0) IS NOT NULL
         THEN s.QTY_ON_HAND / (r.QTY_SOLD_365 / 365.0)
         ELSE NULL END AS COVERAGE_DAYS
FROM inv_snap s
LEFT JOIN sales_365 r
       ON r.S_YEAR       = s.INV_YEAR
      AND r.S_MONTH      = s.INV_MONTH
      AND r.SEGMENT        = s.SEGMENT
      AND r.SUBCATEGORY = s.SUBCATEGORY;

