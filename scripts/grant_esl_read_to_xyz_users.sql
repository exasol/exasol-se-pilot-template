-- XYZ-side ESL read-access overlay
-- ----------------------------------------------------------------------------
-- Grants the XYZ service user access to the external semantic layer schemas so the <PILOT_NAME>
-- Chatbot, the Exasol MCP Server (internal + public — both connect as XYZ_DASH),
-- and the QBR can VIEW the ESL semantic-layer schemas + their objects/metadata.
--
-- XYZ_BIZ is intentionally narrower: it is a business-consumer direct-connect
-- user and must see only:
--   - <SEMANTIC_LAYER_SCHEMA>.BASE_LAYER
--   - <PILOT_SCHEMA>.V_BUSINESS_METRICS
-- Do not grant XYZ_BIZ broad SELECT ON SCHEMA or ESL_POC_ROLE_BUSINESS unless
-- that access model is explicitly re-approved.
--
-- IMPORTANT (CLAUDE.md Rule #13): the ESL layer is <SEMANTIC_LAYER_VENDOR> (<OPS_USER_2> B.) domain.
-- These grants are an XYZ-side OVERLAY — they are NOT part of <SEMANTIC_LAYER_VENDOR> DDL and are
-- NOT regenerated by scripts/extract_external_semantic_layer.py. If <OPS_USER_2> re-deploys / re-creates
-- the ESL schemas + roles, these grants are DROPPED and must be RE-APPLIED with this
-- script. This already happened once: the 2026-06-19 overlay (XYZ-PILOT-269) was wiped
-- by <OPS_USER_2>'s 2026-06-20/21 ESL re-deploy (roles recreated 2026-06-20 18:20, schemas
-- rebuilt 2026-06-21 19:59) — re-applied 2026-06-22. Coordinate any ESL access change
-- with <OPS_USER_2> rather than assuming it persists.
--
-- Structure note (post 2026-06-21 re-deploy): the ESL footprint shrank from 9 schemas
-- to 5. The two virtual schemas (ESL_POC_SEMANTIC_LAYER_VIRTUAL_SCHEMA + _TST), the
-- 50-UDF ESL_SCRIPTS library, and ESL_MODEL are gone; the semantic engine appears
-- consolidated into ESL_POC_SEMANTIC_LAYER_HOME (98 -> 115 objects). The prior
-- ESL_POC_SEMANTIC_LAYER_VIRTUAL_SCHEMA grant target NO LONGER EXISTS and has been
-- removed below.
--
-- Scope:
--   (1) XYZ_DASH: read-only (SELECT ON SCHEMA) on the 4 surviving
--       operator-approved MODEL schemas — makes them visible + metadata-readable
--       to the MCP metadata tools. Deliberately EXCLUDES
--       ESL_POC_SEMANTIC_LAYER_HOME (<SEMANTIC_LAYER_VENDOR> control schema).
--   (2) XYZ_DASH: ESL_POC_ROLE_BUSINESS — the <SEMANTIC_LAYER_VENDOR> business-consumer role
--       (same role BUSINESS_USER01/02/03 hold) for UDF-backed semantic views in
--       <SEMANTIC_LAYER_SCHEMA>.
--   (3) XYZ_BIZ: explicit two-view SELECT only. This is the DBVisualizer /
--       direct-connect business-user contract.
--
-- Run as sys against the target (exapump sql reads a multi-statement script from stdin;
-- `-f` is the output-format flag, NOT a file flag):
--   cat scripts/grant_esl_read_to_xyz_users.sql | exapump sql --profile xyz-pilot
-- Idempotent grant overlay: re-granting an existing privilege / role is a no-op.
--
-- Historical correction: on 2026-06-22, older broad XYZ_BIZ grants from
-- XYZ-PILOT-269/XYZ-PILOT-273 were revoked live:
--   REVOKE ESL_POC_ROLE_BUSINESS FROM XYZ_BIZ;
--   REVOKE SELECT ON SCHEMA <SEMANTIC_LAYER_SCHEMA> FROM XYZ_BIZ;
--   REVOKE SELECT ON SCHEMA ESL_POC_LOGICAL_MODEL FROM XYZ_BIZ;
--   REVOKE SELECT ON SCHEMA ESL_POC_PHYSICAL_MODEL FROM XYZ_BIZ;
-- Do not add those unconditional REVOKEs here; once the cleanup is complete,
-- they fail on re-run. Validate with EXA_DBA_OBJ_PRIVS / EXA_DBA_ROLE_PRIVS
-- instead and revoke only grants that exist.

-- (1) Metadata/read visibility on the 4 surviving model schemas for XYZ_DASH.
GRANT SELECT ON SCHEMA <SEMANTIC_LAYER_SCHEMA> TO XYZ_DASH;
GRANT SELECT ON SCHEMA ESL_POC_LOGICAL_MODEL TO XYZ_DASH;
GRANT SELECT ON SCHEMA ESL_POC_PHYSICAL_MODEL TO XYZ_DASH;
GRANT SELECT ON SCHEMA ESL_POC_RELATIONAL_MODEL TO XYZ_DASH;

-- (2) Execute rights on the UDF-backed semantic (business) views for XYZ_DASH.
GRANT ESL_POC_ROLE_BUSINESS TO XYZ_DASH;

-- (3) Narrow business-user direct-connect contract for XYZ_BIZ.
GRANT SELECT ON <SEMANTIC_LAYER_SCHEMA>.BASE_LAYER TO XYZ_BIZ;
GRANT SELECT ON <PILOT_SCHEMA>.V_BUSINESS_METRICS TO XYZ_BIZ;
